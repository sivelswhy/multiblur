"""Writes the MultiBlur icon for the web app (SVG) and the Android app (adaptive icon vectors).

The macOS and iPhone icons are drawn from the same shapes by macos/tools/make_icon.swift.
Design (512 × 512, top-left origin): a person whose head is a mosaic, inside detection corners,
on a blue-to-indigo gradient.

Usage: python3 scripts/make_icons.py
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

GRADIENT = ("#5B9BFF", "#4A3FE0")
SHADES = ["#FFFFFF", "#DCE3FF", "#B9C5FF", "#95A6F5", "#EEF1FF"]
HEAD = (256, 216, 92)  # center x, center y, radius
CORNERS = (132, 92, 380, 340)  # left, top, right, bottom
ARM, STROKE = 54, 16
# Shoulders, extended past the bottom edge (the icon mask trims them).
BODY = "M81.2,600 L81.2,469 C81.2,349.4 159.9,331 256,331 C352.1,331 430.8,349.4 430.8,469 L430.8,600 Z"


def mosaic_cells():
    """6 × 6 cells over the head, with the same pseudo-random shades as the Swift icon."""
    cx, cy, r = HEAD
    left, top, cell = cx - r, cy - r, 2 * r / 6
    seed, cells = 3, []
    for row in range(6):  # rows count from the bottom, like the Swift drawing
        for col in range(6):
            seed = (seed * 1_103_515_245 + 12_345) & 0xFFFFFFFF
            shade = SHADES[(seed >> 16) % len(SHADES)]
            y = top + (5 - row) * cell
            cells.append((left + col * cell, y, cell, shade))
    return cells


def corner_path():
    l, t, r, b = CORNERS
    return " ".join([
        f"M{l},{t + ARM} L{l},{t} L{l + ARM},{t}",
        f"M{r - ARM},{t} L{r},{t} L{r},{t + ARM}",
        f"M{l},{b - ARM} L{l},{b} L{l + ARM},{b}",
        f"M{r - ARM},{b} L{r},{b} L{r},{b - ARM}",
    ])


def svg() -> str:
    cx, cy, r = HEAD
    cells = "".join(
        f'<rect x="{x:.2f}" y="{y:.2f}" width="{s + 0.5:.2f}" height="{s + 0.5:.2f}" fill="{c}"/>' for x, y, s, c in mosaic_cells()
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
<defs>
<linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{GRADIENT[0]}"/><stop offset="1" stop-color="{GRADIENT[1]}"/></linearGradient>
<clipPath id="tile"><rect width="512" height="512" rx="115"/></clipPath>
<clipPath id="head"><circle cx="{cx}" cy="{cy}" r="{r}"/></clipPath>
</defs>
<g clip-path="url(#tile)">
<rect width="512" height="512" fill="url(#bg)"/>
<path d="{BODY}" fill="#FFFFFF" fill-opacity="0.92"/>
<g clip-path="url(#head)">{cells}</g>
<path d="{corner_path()}" fill="none" stroke="#FFFFFF" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round"/>
</g>
</svg>
"""


def android_background() -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">
                <item android:offset="0" android:color="#FF{GRADIENT[0][1:]}" />
                <item android:offset="1" android:color="#FF{GRADIENT[1][1:]}" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
"""


def android_foreground() -> str:
    # The 512 design scaled to 96 dp and centered: the corners stay inside the 66 dp safe zone.
    scale, offset = 96 / 512, 6
    cx, cy, r = HEAD
    cells = "\n".join(
        f'            <path android:fillColor="#FF{c[1:]}" android:pathData="M{x:.2f},{y:.2f}h{s + 0.5:.2f}v{s + 0.5:.2f}h-{s + 0.5:.2f}z" />'
        for x, y, s, c in mosaic_cells()
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{offset}" android:translateY="{offset}" android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}">
        <path android:fillColor="#EBFFFFFF" android:pathData="{BODY}" />
        <group>
            <clip-path android:pathData="M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 -{2 * r},0" />
{cells}
        </group>
        <path android:strokeColor="#FFFFFFFF" android:strokeWidth="{STROKE}" android:strokeLineCap="round"
            android:strokeLineJoin="round" android:pathData="{corner_path()}" />
    </group>
</vector>
"""


def write(path: str, text: str) -> None:
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w") as f:
        f.write(text)
    print(f"wrote {path}")


if __name__ == "__main__":
    write("web/public/icon.svg", svg())
    write("android/app/src/main/res/drawable/ic_launcher_background.xml", android_background())
    write("android/app/src/main/res/drawable/ic_launcher_foreground.xml", android_foreground())
